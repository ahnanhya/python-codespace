import numpy as arr

array1 = arr.array([1, 2, 3])
array2 = arr.array([4, 5, 6])

addition = arr.add(array1, array2)
subtraction = arr.subtract(array1, array2)
multiplication = arr.multiply(array1, array2)

print(f"Addition of arrays: {addition}")
print(f"Subtraction of arrays: {subtraction}")
print(f"Multiplication of arrays: {multiplication}")
